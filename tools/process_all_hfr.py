#!/usr/bin/env python3
"""process_all_hfr.py — run hfr_preprocess.py on every monthly HF radar dump in a directory.

Each GISTDA dump (YYYYMM_current.sql) holds one *local* (UTC+7) calendar month, so the UTC
window for YYYYMM is [YYYY-MM-01 00:00 − 7 h, next month 00:00 − 7 h). Files run in parallel.

Outputs:
  data/hfr_YYYYMM.js          viewer bundles (lazy-loaded by the viewer via the manifest)
  data/hfr_manifest.js        list of bundles with their time windows and footprints
  analysis/npz/hfr_YYYYMM.npz float32 fields for tools/hfr_spectra.py and tools/hfr_report.py

Example:
  python tools/process_all_hfr.py /path/to/dumps --jobs 6
"""
import argparse
import json
import os
import re
import subprocess
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed
from datetime import datetime, timedelta

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PREPROCESS = os.path.join(HERE, 'hfr_preprocess.py')


def utc_window(ym, local_offset_h):
    y, m = int(ym[:4]), int(ym[4:])
    start = datetime(y, m, 1) - timedelta(hours=local_offset_h)
    end = datetime(y + (m == 12), m % 12 + 1, 1) - timedelta(hours=local_offset_h)
    return start.strftime('%Y-%m-%dT%H:%M'), end.strftime('%Y-%m-%dT%H:%M')


def run_one(path, ym, a):
    start, end = utc_window(ym, a.local_offset_hours)
    cmd = [sys.executable, PREPROCESS, '--sql', path,
           '--cols', 'time_stamp,latitude,longtitude,ucomp,vcomp', '--where', f'sitename={a.site}',
           '--native-xy', 'xdistance,ydistance', '--start', start, '--end', end,
           '--out', os.path.join(a.data_dir, f'hfr_{ym}'),
           '--npz', os.path.join(a.npz_dir, f'hfr_{ym}.npz')]
    p = subprocess.run(cmd, capture_output=True, text=True)
    return ym, p.returncode, p.stdout + p.stderr


def write_manifest(data_dir):
    """Index every data/hfr_*.js bundle (any source) with its time window and footprint."""
    entries = []
    for fn in sorted(os.listdir(data_dir)):
        if not (fn.startswith('hfr_') and fn.endswith('.js')) or fn == 'hfr_manifest.js':
            continue
        js = os.path.join(data_dir, fn)
        with open(js) as fh:
            head = fh.read(4096)
        m = re.search(r'meta: (\{.*?\}), data:', head)
        if not m:
            continue
        meta = json.loads(m.group(1))
        t0 = datetime.fromisoformat(meta['t0'].replace('Z', '+00:00'))
        t1 = t0 + timedelta(hours=meta['stepHours'] * (meta['nFrames'] - 1))
        entries.append({'name': fn[:-3], 'file': f'data/{fn}', 't0': meta['t0'],
                        't1': t1.isoformat().replace('+00:00', 'Z'), 'stepHours': meta['stepHours'],
                        'bbox': [meta['lon0'], meta['lat0'], meta['lon0'] + meta['dlon'] * (meta['nx'] - 1),
                                 meta['lat0'] + meta['dlat'] * (meta['ny'] - 1)],
                        'sizeMB': round(os.path.getsize(js) / 1e6, 1), 'source': meta.get('source', '')})
    entries.sort(key=lambda e: e['t0'])
    path = os.path.join(data_dir, 'hfr_manifest.js')
    with open(path, 'w') as fh:
        fh.write('/* HF radar bundles — generated by tools/process_all_hfr.py / hfr_ncei.py; loaded on demand by main.js */\n')
        fh.write('window.HFR_MANIFEST = ' + json.dumps(entries, indent=1) + ';\n')
    print(f'manifest: {len(entries)} bundles → {path}')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('src', help='directory containing YYYYMM_current.sql dumps')
    ap.add_argument('--site', default='GULF', help='sitename to keep (default GULF)')
    ap.add_argument('--local-offset-hours', type=float, default=7.0, help='dump months are local time (UTC+7)')
    ap.add_argument('--data-dir', default=os.path.join(ROOT, 'data'))
    ap.add_argument('--npz-dir', default=os.path.join(ROOT, 'analysis', 'npz'))
    ap.add_argument('--jobs', type=int, default=max(1, (os.cpu_count() or 2) // 2))
    a = ap.parse_args()

    files = sorted((m.group(1), os.path.join(a.src, f)) for f in os.listdir(a.src)
                   if (m := re.match(r'(\d{6})_current\.sql(\.gz)?$', f)))
    if not files:
        sys.exit(f'No YYYYMM_current.sql files in {a.src}')
    os.makedirs(a.data_dir, exist_ok=True)
    os.makedirs(a.npz_dir, exist_ok=True)
    print(f'{len(files)} dumps, {a.jobs} parallel jobs')

    failed = []
    with ProcessPoolExecutor(a.jobs) as ex:
        futs = [ex.submit(run_one, path, ym, a) for ym, path in files]
        for f in as_completed(futs):
            ym, rc, log = f.result()
            summary = [l for l in log.splitlines() if l.startswith(('native grid', '744', '7', '6', 'wrote')) or 'coverage' in l]
            print(f'── {ym} {"OK" if rc == 0 else "FAILED"}: ' + ' | '.join(summary[-2:]))
            if rc != 0:
                failed.append(ym)
                print(log)

    write_manifest(a.data_dir)
    if failed:
        sys.exit(f'failed: {", ".join(failed)}')


if __name__ == '__main__':
    main()
